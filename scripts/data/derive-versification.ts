/**
 * Derives the chapter and verse counts of the deuterocanonical books from the World English
 * Bible, which is the text that defines their numbering here (the KJV table covers only the 66).
 *
 *   node scripts/data/derive-versification.ts > src/core/bible/deuterocanon-versification.ts
 *
 * A chapter's count is its highest verse *number*, not its number of lines: the Greek numbering
 * of Sirach and Esther skips verses that exist only in the longer Latin text (Sirach 1:5, 1:7, …),
 * and standard editions keep the gaps so that every other verse keeps its number. The WEB
 * writes some of those as empty lines and leaves others out altogether; both become empty verses
 * in the dataset, listed in `scripts/data/lib/omitted-verses.ts`.
 */
import { BOOKS, isDeuterocanonical } from '../../src/core/bible/books.ts';
import { DEUTEROCANON_BOOK_CODES } from './importers/ebible-book-codes.ts';
import { extractZipTextEntry, readFileIfExists } from './lib/files.ts';
import { rawFilePath } from './lib/paths.ts';
import { expectMember, findSource, readSources } from './lib/sources.ts';

const sources = await readSources();
const source = findSource(sources, 'web');
const archive = await readFileIfExists(rawFilePath(source.fileName));
if (!archive) {
  throw new Error(`${source.fileName} is not in data/raw. Run \`npm run data:fetch\` first.`);
}
const text = extractZipTextEntry(archive, expectMember(source));

const highest = new Map<string, Map<number, number>>();
for (const line of text.split(/\r?\n/)) {
  const match = /^(\S+) (\d+):(\d+)/.exec(line);
  if (!match) {
    continue;
  }
  const [, code = '', chapter = '', verse = ''] = match;
  const chapters = highest.get(code) ?? new Map<number, number>();
  chapters.set(Number(chapter), Math.max(chapters.get(Number(chapter)) ?? 0, Number(verse)));
  highest.set(code, chapters);
}

const lines: string[] = [
  "import type { DeuterocanonicalBookId } from './books.ts';",
  '',
  '/**',
  ' * Number of verses in each chapter of each deuterocanonical book, as the World English Bible',
  ' * numbers them (the Greek numbering, with its gaps kept as empty verses).',
  ' *',
  ' * Generated by `scripts/data/derive-versification.ts`; do not edit by hand.',
  ' */',
  'export const DEUTEROCANON_CHAPTER_VERSE_COUNTS: Readonly<',
  '  Record<DeuterocanonicalBookId, readonly number[]>',
  '> = {',
];
for (const book of BOOKS.filter((candidate) => isDeuterocanonical(candidate.id))) {
  const code = DEUTEROCANON_BOOK_CODES[book.id as keyof typeof DEUTEROCANON_BOOK_CODES];
  const chapters = highest.get(code);
  if (!chapters) {
    throw new Error(`The WEB has no book coded ${code} (${book.id}).`);
  }
  const numbers = [...chapters.keys()].sort((a, b) => a - b);
  numbers.forEach((chapter, index) => {
    if (chapter !== index + 1) {
      throw new Error(`${book.id}: chapters are not contiguous (${numbers.join(', ')}).`);
    }
  });
  const counts = numbers.map((chapter) => chapters.get(chapter) ?? 0);
  const key = /^\d/.test(book.id) ? `'${book.id}'` : book.id;
  lines.push(`  ${key}: [${counts.join(', ')}],`);
}
lines.push('};', '');
process.stdout.write(lines.join('\n'));
