import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { DEFAULT_LOCALE_ID, LOCALE_IDS, type LocaleId } from '../src/i18n/locale-id.ts';
import { LOCALE_TAGS } from '../src/i18n/locale-tags.ts';
import { localePathSegment } from '../src/i18n/locale-path.ts';
import {
  SITE_COPY,
  SITE_PAGE_IDS,
  SITE_PAGE_PATHS,
  type SitePageId,
} from '../src/i18n/site-copy.ts';
import { ROOT_DIR } from './site.ts';

/**
 * The HTML entry of every page that is not in the default language.
 *
 * The bundler needs a real file per page, and a page's head is the only place a crawler or a
 * link preview ever reads — so each language gets its own file, with its own title, description
 * and `lang`, written here from `SITE_COPY` rather than copied by hand. `siteHead()` adds the
 * rest of the head to these exactly as it does to the English ones.
 *
 * They are generated into the project root (`pt/index.html`) because that is where their path
 * has to be for the build to publish them at `/pt/`, and they are git-ignored: `SITE_COPY` is
 * the source, and a committed copy would be one more thing to keep in step.
 */

const GENERATED_NOTICE =
  'Generated by vite/locale-entries.ts from src/i18n/site-copy.ts. Do not edit: edit the copy there.';

export function escapeText(value: string): string {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

export function escapeAttribute(value: string): string {
  return escapeText(value).replaceAll('"', '&quot;');
}

/** The entry for one page in one language. */
export function localeEntryHtml(locale: LocaleId, pageId: SitePageId): string {
  const copy = SITE_COPY[locale].pages[pageId];
  return `<!doctype html>
<html lang="${escapeAttribute(LOCALE_TAGS[locale].tag)}" data-theme="dark">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
    <!-- ${GENERATED_NOTICE} -->
    <meta name="description" content="${escapeAttribute(copy.description)}" />
    <title>${escapeText(copy.title)}</title>
  </head>
  <body>
    <div id="root"></div>
    <noscript>${escapeText(copy.noscript)}</noscript>
    <script type="module" src="/src/app/main.tsx"></script>
  </body>
</html>
`;
}

/**
 * Dropped into each generated language directory so that git ignores the whole of it without the
 * root `.gitignore` needing a line per language. Adding a language should mean adding its id to
 * `LOCALE_IDS` and nothing else.
 */
const DIRECTORY_GITIGNORE =
  '# Generated by vite/locale-entries.ts. See src/i18n/site-copy.ts.\n*\n';

/** Every entry this build has to write, as a path relative to the project root. */
export function localeEntries(
  locales: readonly LocaleId[] = LOCALE_IDS,
): readonly { readonly path: string; readonly html: string }[] {
  const entries: { path: string; html: string }[] = [];
  for (const locale of locales) {
    if (locale === DEFAULT_LOCALE_ID) {
      // English is committed (index.html, threads/index.html): it is the template the rest are
      // written from, and the one a contributor edits.
      continue;
    }
    entries.push({ path: `${localePathSegment(locale)}.gitignore`, html: DIRECTORY_GITIGNORE });
    for (const id of SITE_PAGE_IDS) {
      entries.push({
        path: `${localePathSegment(locale)}${SITE_PAGE_PATHS[id]}index.html`,
        html: localeEntryHtml(locale, id),
      });
    }
  }
  return entries;
}

/**
 * Writes the entries, skipping any that is already exactly right.
 *
 * Called while the Vite config is being built, because the bundler needs these files to exist
 * before it reads its inputs — and so the dev server serves them too. Writing nothing when
 * nothing changed keeps the dev server's watcher from reloading in a loop.
 */
export function writeLocaleEntries(
  root: string = ROOT_DIR,
  locales: readonly LocaleId[] = LOCALE_IDS,
): readonly string[] {
  const written: string[] = [];
  for (const { path, html } of localeEntries(locales)) {
    const file = resolve(root, path);
    let current: string | null;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      current = null;
    }
    if (current === html) {
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
    written.push(path);
  }
  return written;
}
